"""Generate extras/screen/screen.ws: a rect-fill pixel screen for a decal wall.

One color output per pixel (px0..pxN-1), each wired in the save to one text
decal's Color.  The wall itself (bricks, decals, wires) is NOT compilable --
the emitter only emits the microchip, logic gates and ports -- so a helper
appends it to screen.brz afterwards (see README).  What the compiler CAN do
is the whole chip: a rect painter into a framebuffer plus a generated
straight-line scanout, because a computed pixel index cannot address ports
and the dispatch chain gives up past ~16 arms.

  python -u extras/screen/gen.py [lanes]     (default 64; writes screen.ws)

Measured shape (audit.py): ~4 nodes per pixel (port + global + scanout copy),
so 64x64 lands ~16.5k nodes.  The painter is K lanes at ~6 nodes each.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

SW, SH = 64, 64
NP = SW * SH
K = int(sys.argv[1]) if len(sys.argv) > 1 else 64

L = []
L.append("// Rect-fill pixel screen, %dx%d, %d painter lanes.  GENERATED by" % (SW, SH, K))
L.append("// gen.py -- edit the generator, not this file.")
L.append("//")
L.append("// One color output per pixel; the save wires each to one brick's property")
L.append("// changer.  Outputs carry NO side annotation: one would place a physical")
L.append("// rerouter pin per port (4096 pins in an 8k-unit line, wrecking the prefab")
L.append("// bounds), and nobody outside needs them -- the wall taps the inner output")
L.append("// gates directly by remote wire.  Only the 7 driven inputs keep @left pins.")
L.append("// The painter walks the latched rect K pixels per tick into fb,")
L.append("// and a generated straight-line scanout mirrors fb into the pixel globals")
L.append("// every tick (a computed index cannot address ports, and an if-chain")
L.append("// past ~16 arms stops taking effect -- so the copy is emitted, not")
L.append("// dispatched).  Unchanged values cost nothing on the wire: ports are")
L.append("// sticky, and re-sending what is already there is not an edit.")
L.append("//")
L.append("// Protocol: pushRect latches one rect (color + bounds), redrawAll paints")
L.append("// the CURRENT drawing (the latched rect, else the last rect again).  Two")
L.append("// signals so the CPU can write its params across ticks and commit")
L.append("// atomically -- no torn rects.  Bounds are normalized (x0>x1 works) and")
L.append("// clipped; a fully off-screen rect paints nothing.  Brick colors persist")
L.append("// until rewritten, so there is no keepalive and no expiry: the chip emits")
L.append("// one rect burst per redrawAll and is silent otherwise.")
L.append("//")
L.append("// Tuning (top of gen.py): LANES is the speed knob (~6 nodes a lane).")
L.append("// Placement is physical: the wall builder lays the 64x64 bricks, so there")
L.append("// are no screen coordinates here.")
L.append("")
L.append('@layout("cube")')
L.append("")
L.append("const SW = %d" % SW)
L.append("const SH = %d" % SH)
L.append("const NP = %d" % NP)
L.append("const SWF = %d.0" % SW)
L.append("const LANES = %d" % K)
L.append("")
L.append("@left in rectColor: color")
L.append("@left in rectX0: float")
L.append("@left in rectY0: float")
L.append("@left in rectX1: float")
L.append("@left in rectY1: float")
L.append("@left in pushRect: bool")
L.append("@left in redrawAll: bool")
L.append("")
L.append("var fb: color[]")
L.append("var fbInit: bool = false")
L.append("var pCol: color = Color(0.0, 0.0, 0.0, 1.0)")
L.append("var pX0: float = 0.0")
L.append("var pY0: float = 0.0")
L.append("var pX1: float = 0.0")
L.append("var pY1: float = 0.0")
L.append("var pending: bool = false")
L.append("var rectOn: bool = false")
L.append("var lt: float = 0.0")
L.append("var area: float = 0.0")
L.append("var rw: float = 1.0")
L.append("var cx0: float = 0.0")
L.append("var cy0: float = 0.0")
for i in range(NP):
    L.append("var g%d: color = Color(0.0, 0.0, 0.0, 1.0)" % i)
    L.append("out px%d: color = g%d" % (i, i))
L.append("")
L.append("// No prev-edge flags anywhere in this file, deliberately.  on Change fires")
L.append("// only on a transition, so the event IS the edge.  A same-handler")
L.append("// read-then-write of one var loses the race; cross-handler flags")
L.append("// (pending, rectOn) are fine, because no pass writes what it reads.")
L.append("on Change(pushRect) {")
L.append("  if pushRect {")
L.append("    pCol = rectColor")
L.append("    pX0 = rectX0")
L.append("    pY0 = rectY0")
L.append("    pX1 = rectX1")
L.append("    pY1 = rectY1")
L.append("    pending = true")
L.append("  }")
L.append("}")
L.append("")
L.append("// redrawAll repaints the CURRENT drawing: the latched rect if pushRect staged")
L.append("// one, else the last rect again.  Either way exactly one rect's pixels land")
L.append("// in fb; the scanout below carries them to the ports.")
L.append("on Change(redrawAll) {")
L.append("  if redrawAll {")
L.append("    if pending {")
L.append("      let ax0 = if pX0 < pX1 then pX0 else pX1")
L.append("      let ax1 = if pX0 < pX1 then pX1 else pX0")
L.append("      let ay0 = if pY0 < pY1 then pY0 else pY1")
L.append("      let ay1 = if pY0 < pY1 then pY1 else pY0")
L.append("      if ax1 < 0.0 || ax0 >= SWF || ay1 < 0.0 || ay0 >= SWF {")
L.append("        pending = false")
L.append("      } else {")
L.append("        cx0 = if ax0 < 0.0 then 0.0 else if ax0 >= SWF then SWF - 1.0 else ax0")
L.append("        cy0 = if ay0 < 0.0 then 0.0 else if ay0 >= SWF then SWF - 1.0 else ay0")
L.append("        let ex1 = if ax1 < 0.0 then 0.0 else if ax1 >= SWF then SWF - 1.0 else ax1")
L.append("        let ey1 = if ay1 < 0.0 then 0.0 else if ay1 >= SWF then SWF - 1.0 else ay1")
L.append("        rw = ex1 - cx0 + 1.0")
L.append("        area = rw * (ey1 - cy0 + 1.0)")
L.append("        lt = 0.0")
L.append("        rectOn = true")
L.append("        pending = false")
L.append("      }")
L.append("    }")
L.append("    // Replay is a SEPARATE depth-1 if, not an else-if of the arming above.")
L.append("    // Sequential flat ifs keep every arm observable and every outcome")
L.append("    // correct: firing right after an arming restates the same state, and")
L.append("    // !rectOn keeps a mid-burst redrawAll from restarting the burst.")
L.append("    if area > 0.0 && !rectOn {")
L.append("      lt = 0.0")
L.append("      rectOn = true")
L.append("    }")
L.append("  }")
L.append("}")
L.append("")
L.append("// Array writes live in a mod, not the handler body: the compiler reports")
L.append("// array index access outside an exec context as WS007.  There is no %")
L.append("// operator, so remainders are floor-based (all values here are")
L.append("// non-negative, so truncation is floor).")
L.append("mod paintTick() {")
L.append("  if !fbInit {")
L.append("    fb.resize(NP, Color(0.0, 0.0, 0.0, 1.0))")
L.append("    fbInit = true")
L.append("  }")
L.append("  if rectOn {")
for j in range(K):
    L.append("    let tt%d = lt + %d.0" % (j, j))
    L.append("    if tt%d < area {" % j)
    L.append("      let qd%d = (((tt%d / rw) | 0) + 0.0)" % (j, j))
    L.append("      let lx%d = cx0 + (tt%d - qd%d * rw)" % (j, j, j))
    L.append("      let ly%d = cy0 + qd%d" % (j, j))
    L.append("      let ridx%d = ((ly%d * SWF + lx%d) | 0)" % (j, j, j))
    L.append("      fb[ridx%d] = pCol" % j)
    L.append("    }")
L.append("    lt = lt + %d.0" % K)
L.append("    if lt >= area {")
L.append("      rectOn = false")
L.append("    }")
L.append("  }")
L.append("  // The scanout: every pixel global mirrors its fb slot, every tick.")
for i in range(NP):
    L.append("  g%d = fb[%d]" % (i, i))
L.append("}")
L.append("")
L.append("on Clock(interval = 0.01) {")
L.append("  paintTick()")
L.append("}")
path = os.path.join(HERE, "screen.ws")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", path, "lanes", K)
