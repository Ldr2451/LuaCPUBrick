# ---- point transform: staged points -> world space ----------------------
# Runs once per staged shape, after the shadow/slot load and before
# either arm.  The world transform (own locals composed through every
# ancestor) is resolved from the staging vars and the slot store, then
# the 16 staged points are transformed in place.  All three vector
# fields are live: shapePosition.xyz translates, shapeRotation.xyz
# rotates (radians, R = Rz*Ry*Rx, off-axis tilt foreshortens),
# shapeScale.xyz scales (zeroes mean identity).  A 3D shape (an odd
# staged length) also transforms each point's own z, and the result is
# projected: screen = EYE * world / (EYE + world.z), the eye sitting at
# z = -EYE, with the denominator clamped at 1.0.  Projection happens
# AFTER the whole ancestor chain, so a parent's rotation is part of the
# point before the divide.  World z (not the projected depth) is what the
# fill's depth buffer tests, so faces keep ordering by how far they are.
# The ancestor walk is straight-line and capped at WALK steps (every slot
# index, so the deepest acyclic chain): a dead parent resolves to identity
# above it; a cycle revisits and paints its WALK-fold composition.  With no tilt anywhere in the chain and a 2D shape
# the legacy planar path runs bit-identically to before (same op order)
