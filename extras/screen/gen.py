"""Generate extras/screen/screen.ws: a rect-fill pixel screen with no outputs.

Pixels are player-screen overlay texts (DisplayText gates with stable textIds),
one gate per painter lane, reused across ticks -- so NOTHING in the graph scales
with the pixel count.  A 64x64 screen costs painter lanes plus control logic,
not 4096 of anything.  The only things that scale are the framebuffer array
(memory, not nodes) and the textId range.

  python -u extras/screen/gen.py [lanes]     (default 16; writes screen.ws)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

SW, SH = 64, 64
NP = SW * SH
MGX, MGY, CELL = 20.0, 20.0, 10.0
FSIZE = 10
TIDB = 1000
LIFE = 10.0
K = int(sys.argv[1]) if len(sys.argv) > 1 else 64
GLYPH = chr(9608)  # FULL BLOCK: fills the text cell edge to edge, no grid gaps

L = []
L.append("// Rect-fill pixel screen, %dx%d, %d painter lanes.  GENERATED by" % (SW, SH, K))
L.append("// gen.py -- edit the generator, not this file.  No output ports: pixels")
L.append("// are DisplayText overlays with stable textIds, repainted in place.")
L.append("//")
L.append("// Protocol: pushRect latches the rect, redraw paints it.  Two signals so")
L.append("// the CPU can write its params across ticks and commit atomically.")
L.append("// posLeft/posUp pick the anchor corner as screen fractions (0 = left/top,")
L.append("// 1 = right/bottom -- the documented anchor/offset placement), and every")
L.append("// pixel offsets INWARD from it in slate units (~pixels at 1080p).  Anchors")
L.append("// are absolute, so orientation cannot mirror, and a 20 + 63*10 = 650-unit")
L.append("// grid fits a 1080p screen from any corner.")
L.append("// persistAll=true keeps a keepalive sweep running so pixels never expire;")
L.append("// persistAll=false re-shows the frame once per input update and lets it")
L.append("// expire after LIFE.")
L.append("//")
L.append("// Tuning (all consts, top of gen.py): MGX/MGY/CELL place and size the grid,")
L.append("// FSIZE should match CELL, TIDB must not collide with other overlays,")
L.append("// LIFE must exceed a full keepalive sweep (4096/K ticks).")
L.append("// One chip shows to ONE player: wire that viewer's character in.")
L.append("")
L.append('@layout("cube")')
L.append("")
L.append("const SW = %d" % SW)
L.append("const SH = %d" % SH)
L.append("const NP = %d" % NP)
L.append("const SWF = %d.0" % SW)
L.append("const MGX = %s" % MGX)
L.append("const MGY = %s" % MGY)
L.append("const CELL = %s" % CELL)
L.append("const FSIZE = %d" % FSIZE)
L.append("const TIDB = %d" % TIDB)
L.append("const LIFE = %s" % LIFE)
L.append("const LANES = %d" % K)
L.append("const NPF = %d.0" % NP)
L.append("")
L.append("@left in player: character")
L.append("@left in rectColor: color")
L.append("@left in rX0: float")
L.append("@left in rY0: float")
L.append("@left in rX1: float")
L.append("@left in rY1: float")
L.append("@left in pushRect: bool")
L.append("@left in redraw: bool")
L.append("@left in posLeft: bool")
L.append("@left in posUp: bool")
L.append("@left in persistAll: bool")
L.append("")
L.append("var fb: color[]")
L.append("var fbInit: bool = false")
L.append("var ctrl: controller")
L.append("var pCol: color = Color(1.0, 1.0, 1.0, 1.0)")
L.append("var pX0: float = 0.0")
L.append("var pY0: float = 0.0")
L.append("var pX1: float = 0.0")
L.append("var pY1: float = 0.0")
L.append("var pending: bool = false")
L.append("var rectOn: bool = false")
L.append("var lt: float = 0.0")
L.append("var area: float = 0.0")
L.append("var rw: float = 1.0")
L.append("var cx0: float = 0.0")
L.append("var cy0: float = 0.0")
L.append("var s: float = 0.0")
L.append("var sweepLeft: float = 0.0")
L.append("var cornerAX: float = 0.0")
L.append("var cornerAY: float = 0.0")
L.append("var persistAllV: bool = false")
L.append("")
L.append("// No prev-edge flags anywhere in this file, deliberately.  on Change fires")
L.append("// only on a transition, so the event IS the edge and `if pushRect` latches")
L.append("// exactly on rising.  An earlier version kept `prevRefresh`/`prevRedraw`")
L.append("// with a write-after tail (`prevRefresh = refresh`), and the tail won the")
L.append("// race: it executed before the branch re-read the flag, so every real edge")
L.append("// evaluated false and refresh never latched.  A same-handler read-then-write")
L.append("// of one var is the shape to never write; cross-handler (pending, rectOn)")
L.append("// is fine, because no pass writes what it reads.")
L.append("on Change(pushRect) {")
L.append("  if pushRect {")
L.append("    pCol = rectColor")
L.append("    pX0 = rX0")
L.append("    pY0 = rY0")
L.append("    pX1 = rX1")
L.append("    pY1 = rY1")
L.append("    cornerAX = if posLeft then 0.0 else 1.0")
L.append("    cornerAY = if posUp then 0.0 else 1.0")
L.append("    pending = true")
L.append("    if !persistAllV {")
L.append("      sweepLeft = NPF")
L.append("    }")
L.append("  }")
L.append("}")
L.append("")
L.append("on Change(persistAll) {")
L.append("  persistAllV = persistAll")
L.append("}")
L.append("")
L.append("on Change(redraw) {")
L.append("  if redraw && pending && !rectOn {")
L.append("    cornerAX = if posLeft then 0.0 else 1.0")
L.append("    cornerAY = if posUp then 0.0 else 1.0")
L.append("    let ax0 = if pX0 < pX1 then pX0 else pX1")
L.append("    let ax1 = if pX0 < pX1 then pX1 else pX0")
L.append("    let ay0 = if pY0 < pY1 then pY0 else pY1")
L.append("    let ay1 = if pY0 < pY1 then pY1 else pY0")
L.append("    if ax1 < 0.0 || ax0 >= SWF || ay1 < 0.0 || ay0 >= SWF {")
L.append("      pending = false")
L.append("      if !persistAllV {")
L.append("        sweepLeft = NPF")
L.append("      }")
L.append("    } else {")
L.append("      cx0 = if ax0 < 0.0 then 0.0 else if ax0 >= SWF then SWF - 1.0 else ax0")
L.append("      cy0 = if ay0 < 0.0 then 0.0 else if ay0 >= SWF then SWF - 1.0 else ay0")
L.append("      let ex1 = if ax1 < 0.0 then 0.0 else if ax1 >= SWF then SWF - 1.0 else ax1")
L.append("      let ey1 = if ay1 < 0.0 then 0.0 else if ay1 >= SWF then SWF - 1.0 else ay1")
L.append("      rw = ex1 - cx0 + 1.0")
L.append("      area = rw * (ey1 - cy0 + 1.0)")
L.append("      lt = 0.0")
L.append("      rectOn = true")
L.append("      pending = false")
L.append("      if !persistAllV {")
L.append("        sweepLeft = NPF")
L.append("      }")
L.append("    }")
L.append("  }")
L.append("}")
L.append("")
L.append("// Array reads and DisplayText live in a mod, not the handler body: the")
L.append("// compiler reports both as WS007 outside an exec context, and a mod")
L.append("// containing DisplayText calls is the shape the compiler's own 2048")
L.append("// example uses (its renderCell).  There is no % operator, so remainders")
L.append("// are floor-based (all values here are non-negative, so truncation is")
L.append("// floor) and the sweep cursor wraps by subtract, one step being < NP.")
L.append("mod paintTick() {")
L.append("  if !fbInit {")
L.append("    // Opaque white: the grid reads as a screen, not a hole, and a")
L.append("    // first rect shows against it without needing a clear first.")
L.append("    fb.resize(NP, Color(1.0, 1.0, 1.0, 1.0))")
L.append("    fbInit = true")
L.append("  }")
L.append("  ctrl = ControllerOf(player)")
L.append("  if rectOn {")
for j in range(K):
    L.append("    let tt%d = lt + %d.0" % (j, j))
    L.append("    if tt%d < area {" % j)
    L.append("      let qd%d = (((tt%d / rw) | 0) + 0.0)" % (j, j))
    L.append("      let lx%d = cx0 + (tt%d - qd%d * rw)" % (j, j, j))
    L.append("      let ly%d = cy0 + qd%d" % (j, j))
    L.append("      let ridx%d = ((ly%d * SWF + lx%d) | 0)" % (j, j, j))
    L.append("      fb[ridx%d] = pCol" % j)
    L.append("      let ox%d = if cornerAX < 0.5 then MGX + lx%d * CELL else 0.0 - (MGX + lx%d * CELL)" % (j, j, j))
    L.append("      let oy%d = if cornerAY < 0.5 then MGY + ly%d * CELL else 0.0 - (MGY + ly%d * CELL)" % (j, j, j))
    L.append("      DisplayText(ctrl, \"%s\", positionX = ox%d, positionY = oy%d, anchorX = cornerAX, anchorY = cornerAY, fontColor = pCol, fontSize = FSIZE, "
             "lifetime = LIFE, textId = TIDB + ridx%d)" % (GLYPH, j, j, j))
    L.append("    }")
L.append("    lt = lt + %d.0" % K)
L.append("    if lt >= area {")
L.append("      rectOn = false")
L.append("    }")
L.append("  } else {")
L.append("    // The keepalive sweep runs continuously with persistAll, or one full pass")
L.append("    // per input update without it (sweepLeft counts that pass down).  Either")
L.append("    // way every pixel is re-emitted inside LIFE; without persist the pixels")
L.append("    // then expire until the next update re-shows them.")
L.append("    if persistAllV || sweepLeft > 0.0 {")
for j in range(K):
    L.append("      let sp%d = if s + %d.0 >= NPF then s + %d.0 - NPF else s + %d.0"
             % (j, j, j, j))
    L.append("      let sy%d = ((sp%d / SWF) | 0)" % (j, j))
    L.append("      let sx%d = ((sp%d - (sy%d + 0.0) * SWF) | 0)" % (j, j, j))
    L.append("      let sidx%d = (sp%d | 0)" % (j, j))
    L.append("      let qx%d = if cornerAX < 0.5 then MGX + (sx%d + 0.0) * CELL else 0.0 - (MGX + (sx%d + 0.0) * CELL)" % (j, j, j))
    L.append("      let qy%d = if cornerAY < 0.5 then MGY + (sy%d + 0.0) * CELL else 0.0 - (MGY + (sy%d + 0.0) * CELL)" % (j, j, j))
    L.append("      DisplayText(ctrl, \"%s\", positionX = qx%d, positionY = qy%d, anchorX = cornerAX, anchorY = cornerAY, fontColor = fb[sidx%d], "
             "fontSize = FSIZE, lifetime = LIFE, textId = TIDB + sidx%d)"
             % (GLYPH, j, j, j, j))
L.append("      s = if s + %d.0 >= NPF then s + %d.0 - NPF else s + %d.0"
         % (K, K, K))
L.append("      if sweepLeft > 0.0 {")
L.append("        sweepLeft = sweepLeft - %d.0" % K)
L.append("      }")
L.append("    }")
L.append("  }")
L.append("}")
L.append("")
L.append("on Clock(interval = 0.01) {")
L.append("  paintTick()")
L.append("}")
path = os.path.join(HERE, "screen.ws")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", path, "lanes", K)
