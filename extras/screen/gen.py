"""Generate extras/screen/screen.ws: a rect- and triangle-fill pixel
screen for a microbrick wall.

One color output per pixel (px0..pxN-1), each wired in the save to one text
decal's Color.  The wall itself (bricks, decals, wires) is NOT compilable --
the emitter only emits the microchip, logic gates and ports -- so a helper
appends it to screen.brz afterwards (see README).  What the compiler CAN do
is the whole chip: a rect painter into a framebuffer plus a generated
straight-line scanout, because a computed pixel index cannot address ports
and the dispatch chain gives up past ~16 arms.

  python -u extras/screen/gen.py [lanes]     (default 64; writes screen.ws)

Measured shape (audit.py): ~4 nodes per pixel (port + global + scanout copy),
so 64x64 lands ~16.5k nodes.  The painter is K lanes at ~6 nodes each.
"""
import itertools
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

SW, SH = 64, 64
NP = SW * SH
K = int(sys.argv[1]) if len(sys.argv) > 1 else 64

# The three staged triangle vertices, for the sort arms in the arm code
# and for the test model, which replays the same arms in the same order.
names = [("tX0", "tY0"), ("tX1", "tY1"), ("tX2", "tY2")]


def span_lines(indent):
    """The current row's pixel span, shared by the arm and the walk.

    The row is crossed by the long edge A->C and one more: A->B above the
    middle vertex, B->C below it.  min/max makes winding irrelevant.  A
    span entirely off screen is marked empty (tSpanL=1, tSpanR=-1), so the
    lanes paint nothing and the walk's `tCol > tSpanR` check advances on
    its own -- no special case in either caller.  `sl | 0` is the floor of
    a non-negative clamped bound, which is the pixel the span starts on.
    """
    p = indent
    return [
        p + "let ex = if tRow < vBy then vAx + sAB * (tRow - vAy) else"
            " vBx + sBC * (tRow - vBy)",
        p + "let fx = vAx + sAC * (tRow - vAy)",
        p + "let sl = if ex < fx then ex else fx",
        p + "let sr = if ex < fx then fx else ex",
        p + "if sl >= SWF || sr < 0.0 {",
        p + "  tSpanL = 1.0",
        p + "  tSpanR = -1.0",
        p + "} else {",
        p + "  tSpanL = if sl < 0.0 then 0.0 else (sl | 0)",
        p + "  tSpanR = if sr >= SWF then SWF - 1.0 else (sr | 0)",
        p + "}",
    ]

L = []
L.append("// Rect-fill pixel screen, %dx%d, %d painter lanes.  GENERATED by" % (SW, SH, K))
L.append("// gen.py -- edit the generator, not this file.")
L.append("//")
L.append("// One color output per pixel; the save wires each to one brick's property")
L.append("// changer.  Outputs carry NO side annotation: one would place a physical")
L.append("// rerouter pin per port (4096 pins in an 8k-unit line, wrecking the prefab")
L.append("// bounds), and nobody outside needs them -- the wall taps the inner output")
L.append("// gates directly by remote wire.  Only the 7 driven inputs keep @left pins.")
L.append("// The painter walks the latched rect K pixels per tick into fb,")
L.append("// and a generated straight-line scanout mirrors fb into the pixel globals")
L.append("// every tick (a computed index cannot address ports, and an if-chain")
L.append("// past ~16 arms stops taking effect -- so the copy is emitted, not")
L.append("// dispatched).  Unchanged values cost nothing on the wire: ports are")
L.append("// sticky, and re-sending what is already there is not an edit.")
L.append("//")
L.append("// Protocol: pushRect latches one rect (color + bounds), pushTri latches")
L.append("// a triangle (the same four bound pins as the first two vertices plus")
L.append("// triX2/triY2 for the third), and redrawAll paints the CURRENT")
L.append("// drawing: the latched shape, else the last rect again (a triangle")
L.append("// replays from its first row).  Two stage signals so the CPU can write")
L.append("// its params across ticks and commit atomically -- no torn shapes; the")
L.append("// last push before a redrawAll wins.  Rect bounds are normalized")
L.append("// (x0>x1 works) and clipped; a fully off-screen shape paints nothing.")
L.append("// Brick colors persist until rewritten, so there is no keepalive and no")
L.append("// expiry: the chip emits one burst per redrawAll and is silent")
L.append("// otherwise.")
L.append("//")
L.append("// Shapes paint at different speeds by construction.  A rect walks its")
L.append("// bounding box row-major, so a burst is ceil(area/64) ticks.  A triangle")
L.append("// walks spans row by row, so a burst is one tick per row -- the honest")
L.append("// price of a shape that is not a rectangle.  Clearing the wall is still")
L.append("// one rect command; a triangle clear is two.")
L.append("//")
L.append("// Tuning (top of gen.py): LANES is the speed knob (~6 nodes a lane).")
L.append("// Placement is physical: the wall builder lays the 64x64 bricks, so there")
L.append("// are no screen coordinates here.")
L.append("")
L.append('@layout("cube")')
L.append("")
L.append("const SW = %d" % SW)
L.append("const SH = %d" % SH)
L.append("const NP = %d" % NP)
L.append("const SWF = %d.0" % SW)
L.append("const LANES = %d" % K)
L.append("")
L.append("@left in rectColor: color")
L.append("@left in rectX0: float")
L.append("@left in rectY0: float")
L.append("@left in rectX1: float")
L.append("@left in rectY1: float")
L.append("@left in triX2: float")
L.append("@left in triY2: float")
L.append("@left in pushRect: bool")
L.append("@left in pushTri: bool")
L.append("@left in redrawAll: bool")
L.append("")
L.append("var fb: color[]")
L.append("var fbInit: bool = false")
L.append("var pCol: color = Color(0.0, 0.0, 0.0, 1.0)")
L.append("var pX0: float = 0.0")
L.append("var pY0: float = 0.0")
L.append("var pX1: float = 0.0")
L.append("var pY1: float = 0.0")
L.append("var pending: bool = false")
L.append("var rectOn: bool = false")
L.append("var lt: float = 0.0")
L.append("var area: float = 0.0")
L.append("var rw: float = 1.0")
L.append("var cx0: float = 0.0")
L.append("var cy0: float = 0.0")
# Triangle state.  tX0..tY2 stage the three vertices (the first two reuse
# the shared bound pins), the v* slots hold them sorted by y (A<=B<=C),
# sAB/sAC/sBC are the edge slopes, and the walk is tRow/tCol/tSpanL/tSpanR
# with tOn/tLive/pTri as its live / replayable / pending flags.
L.append("var tX0: float = 0.0")
L.append("var tY0: float = 0.0")
L.append("var tX1: float = 0.0")
L.append("var tY1: float = 0.0")
L.append("var tX2: float = 0.0")
L.append("var tY2: float = 0.0")
L.append("var tCol: float = 0.0")
L.append("var tRow: float = 0.0")
L.append("var tSpanL: float = 0.0")
L.append("var tSpanR: float = 0.0")
L.append("var tFirstRow: float = 0.0")
L.append("var tLastRow: float = 0.0")
L.append("var sAB: float = 0.0")
L.append("var sAC: float = 0.0")
L.append("var sBC: float = 0.0")
L.append("var vAx: float = 0.0")
L.append("var vAy: float = 0.0")
L.append("var vBx: float = 0.0")
L.append("var vBy: float = 0.0")
L.append("var vCx: float = 0.0")
L.append("var vCy: float = 0.0")
L.append("var pTri: bool = false")
L.append("var tOn: bool = false")
L.append("var tLive: bool = false")
for i in range(NP):
    L.append("var g%d: color = Color(0.0, 0.0, 0.0, 1.0)" % i)
    L.append("out px%d: color = g%d" % (i, i))
L.append("")
L.append("// No prev-edge flags anywhere in this file, deliberately.  on Change fires")
L.append("// only on a transition, so the event IS the edge.  A same-handler")
L.append("// read-then-write of one var loses the race; cross-handler flags")
L.append("// (pending, rectOn) are fine, because no pass writes what it reads.")
L.append("on Change(pushRect) {")
L.append("  if pushRect {")
L.append("    pCol = rectColor")
L.append("    pX0 = rectX0")
L.append("    pY0 = rectY0")
L.append("    pX1 = rectX1")
L.append("    pY1 = rectY1")
L.append("    pending = true")
L.append("    pTri = false")
L.append("  }")
L.append("}")
L.append("")
L.append("// A triangle latches the same four bound pins (the first two vertices)")
L.append("// plus the third point's own two.  Each push clears the other shape's")
L.append("// stage, so the last push before a redrawAll is the one that arms -- and")
L.append("// a load-time edge on an unwired stage cannot fire later.")
L.append("on Change(pushTri) {")
L.append("  if pushTri {")
L.append("    pCol = rectColor")
L.append("    tX0 = rectX0")
L.append("    tY0 = rectY0")
L.append("    tX1 = rectX1")
L.append("    tY1 = rectY1")
L.append("    tX2 = triX2")
L.append("    tY2 = triY2")
L.append("    pTri = true")
L.append("    pending = false")
L.append("  }")
L.append("}")
L.append("")
L.append("// redrawAll repaints the CURRENT drawing: the latched rect if pushRect staged")
L.append("// one, else the last rect again.  Either way exactly one rect's pixels land")
L.append("// in fb; the scanout below carries them to the ports.")
L.append("on Change(redrawAll) {")
L.append("  if redrawAll {")
L.append("    if pending {")
L.append("      let ax0 = if pX0 < pX1 then pX0 else pX1")
L.append("      let ax1 = if pX0 < pX1 then pX1 else pX0")
L.append("      let ay0 = if pY0 < pY1 then pY0 else pY1")
L.append("      let ay1 = if pY0 < pY1 then pY1 else pY0")
L.append("      if ax1 < 0.0 || ax0 >= SWF || ay1 < 0.0 || ay0 >= SWF {")
L.append("        pending = false")
L.append("      } else {")
L.append("        cx0 = if ax0 < 0.0 then 0.0 else if ax0 >= SWF then SWF - 1.0 else ax0")
L.append("        cy0 = if ay0 < 0.0 then 0.0 else if ay0 >= SWF then SWF - 1.0 else ay0")
L.append("        let ex1 = if ax1 < 0.0 then 0.0 else if ax1 >= SWF then SWF - 1.0 else ax1")
L.append("        let ey1 = if ay1 < 0.0 then 0.0 else if ay1 >= SWF then SWF - 1.0 else ay1")
L.append("        rw = ex1 - cx0 + 1.0")
L.append("        area = rw * (ey1 - cy0 + 1.0)")
L.append("        lt = 0.0")
L.append("        rectOn = true")
L.append("        pending = false")
L.append("        tOn = false")
L.append("      }")
L.append("    }")
# A triangle stage arms after the rect stage, so the last push before a
# redrawAll wins and the other walk is abandoned mid-burst (a re-arm
# restarts a burst, so exactly one walk may be live).
L.append("    if pTri {")
# Sort the three vertices by y into A<=B<=C.  Flat ifs, last match wins
# on ties (degenerate anyway); painttest replays these six arms in the
# same order, so chip and test agree by construction.
for i, j, k in itertools.permutations((0, 1, 2)):
    xi, yi = names[i]
    xj, yj = names[j]
    xk, yk = names[k]
    L.append("      if %s <= %s && %s <= %s {" % (yi, yj, yj, yk))
    L.append("        vAx = %s" % xi)
    L.append("        vAy = %s" % yi)
    L.append("        vBx = %s" % xj)
    L.append("        vBy = %s" % yj)
    L.append("        vCx = %s" % xk)
    L.append("        vCy = %s" % yk)
    L.append("      }")
# Edge slopes, each guarded: a flat edge would divide by zero.
L.append("      let dyAB = vBy - vAy")
L.append("      sAB = if dyAB > 0.0 then (vBx - vAx) / dyAB else 0.0")
L.append("      let dyAC = vCy - vAy")
L.append("      sAC = if dyAC > 0.0 then (vCx - vAx) / dyAC else 0.0")
L.append("      let dyBC = vCy - vBy")
L.append("      sBC = if dyBC > 0.0 then (vCx - vBx) / dyBC else 0.0")
# Fully off screen: no rows at all, and nothing replayable.
L.append("      let vxmin = if vAx < vBx then (if vAx < vCx then vAx"
         " else vCx) else (if vBx < vCx then vBx else vCx)")
L.append("      let vxmax = if vAx > vBx then (if vAx > vCx then vAx"
         " else vCx) else (if vBx > vCx then vBx else vCx)")
L.append("      if vCy >= 0.0 && vAy < SWF && vxmax >= 0.0"
         " && vxmin < SWF {")
L.append("        tFirstRow = if vAy < 0.0 then 0.0 else (vAy | 0)")
L.append("        tLastRow = if vCy >= SWF then SWF - 1.0 else (vCy | 0)")
L.append("        tRow = tFirstRow")
L += span_lines("        ")
L.append("        tCol = tSpanL")
L.append("        tOn = true")
L.append("        tLive = true")
L.append("      }")
L.append("      rectOn = false")
L.append("      pTri = false")
L.append("    }")
L.append("    // Replay is a SEPARATE depth-1 if, not an else-if of the arming above.")
L.append("    // Sequential flat ifs keep every arm observable and every outcome")
L.append("    // correct: firing right after an arming restates the same state, and")
L.append("    // !rectOn keeps a mid-burst redrawAll from restarting the burst.  The")
L.append("    // !tOn guards keep a triangle walk and a rect replay from colliding.")
L.append("    if area > 0.0 && !rectOn && !tOn {")
L.append("      lt = 0.0")
L.append("      rectOn = true")
L.append("    }")
L.append("    // A triangle replay restarts the walk from its first row: vertices,")
L.append("    // slopes and the first row's span are still staged, so the walk state")
L.append("    // is all that resets.")
L.append("    if tLive && !tOn && !rectOn {")
L.append("      tRow = tFirstRow")
L.append("      tCol = tSpanL")
L.append("      tOn = true")
L.append("    }")
L.append("  }")
L.append("}")
L.append("")
L.append("// Array writes live in a mod, not the handler body: the compiler reports")
L.append("// array index access outside an exec context as WS007.  There is no %")
L.append("// operator, so remainders are floor-based (all values here are")
L.append("// non-negative, so truncation is floor).")
L.append("mod paintTick() {")
L.append("  if !fbInit {")
L.append("    fb.resize(NP, Color(0.0, 0.0, 0.0, 1.0))")
L.append("    fbInit = true")
L.append("  }")
L.append("  if rectOn {")
for j in range(K):
    L.append("    let tt%d = lt + %d.0" % (j, j))
    L.append("    if tt%d < area {" % j)
    L.append("      let qd%d = (((tt%d / rw) | 0) + 0.0)" % (j, j))
    L.append("      let lx%d = cx0 + (tt%d - qd%d * rw)" % (j, j, j))
    L.append("      let ly%d = cy0 + qd%d" % (j, j))
    L.append("      let ridx%d = ((ly%d * SWF + lx%d) | 0)" % (j, j, j))
    L.append("      fb[ridx%d] = pCol" % j)
    L.append("    }")
L.append("    lt = lt + %d.0" % K)
L.append("    if lt >= area {")
L.append("      rectOn = false")
L.append("    }")
L.append("  }")
# The triangle walk: one row per tick.  The mod recomputes the current
# row's span when the previous row ran out, then the lanes fill it left
# to right; a row wider than LANES continues next tick.  A burst costs
# one tick per row rather than one per 64 px -- the honest price of a
# shape that is not a rectangle.  rectOn and tOn are mutually exclusive
# (the arm clears the other), so the two walks never interleave.
L.append("  if tOn {")
L.append("    if tCol > tSpanR {")
L.append("      tRow = tRow + 1.0")
L.append("      if tRow > tLastRow {")
L.append("        tOn = false")
L.append("      } else {")
L += span_lines("        ")
L.append("        tCol = tSpanL")
L.append("      }")
L.append("    }")
L.append("    if tOn {")
for j in range(K):
    L.append("      let tj%d = tCol + %d.0" % (j, j))
    L.append("      if tj%d <= tSpanR {" % j)
    L.append("        let ridx%d = ((tRow * SWF + tj%d) | 0)" % (j, j))
    L.append("        fb[ridx%d] = pCol" % j)
    L.append("      }")
L.append("      tCol = tCol + %d.0" % K)
L.append("    }")
L.append("  }")
L.append("  // The scanout: every pixel global mirrors its fb slot, every tick.")
for i in range(NP):
    L.append("  g%d = fb[%d]" % (i, i))
L.append("}")
L.append("")
L.append("on Clock(interval = 0.01) {")
L.append("  paintTick()")
L.append("}")
path = os.path.join(HERE, "screen.ws")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", path, "lanes", K)
